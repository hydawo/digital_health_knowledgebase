#!/usr/bin/env python3
"""Build one hub page per Module 5 domain from the domain tags and the domain catalogue.

    python3 tools/domains/build_hubs.py          # write every hub
    python3 tools/domains/build_hubs.py --check  # exit 1 if a hub is out of date

Reads shared/domain-tags.json (papers and profiles in Modules 1 to 4 tagged with a domain) and
module-05-measurement-science/<domain>/literature-library.md, and writes
module-05-measurement-science/<domain>/hub.md. The hub is generated: edit the tags or the
catalogue, never the hub.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TAGS = os.path.join(ROOT, 'shared', 'domain-tags.json')
M5 = os.path.join(ROOT, 'module-05-measurement-science')
MODULE_NAMES = {1: 'Module 1, wearables', 2: 'Module 2, digital phenotyping',
                3: 'Module 3, applied studies', 4: 'Module 4, methods and reviews'}
KIND_LABEL = {'m1-profile': 'Module 1 profile', 'm2-profile': 'Module 2 profile'}


def catalogue_rows(domain):
    """Rows of the domain catalogue as (section, id, title, venue_year) tuples."""
    rows, section = [], None
    path = os.path.join(M5, domain, 'literature-library.md')
    for line in open(path, encoding='utf-8'):
        if line.startswith('## '):
            section = line[3:].strip()
        elif line.startswith('| ') and not line.startswith(('| #', '|---')):
            cells = [c.strip() for c in line.strip().strip('|').split('|')]
            if len(cells) >= 4:
                rows.append((section, cells[0], cells[1], cells[3]))
    return rows


def link(path):
    """Relative link from module-05-measurement-science/<domain>/hub.md to a repo path."""
    return '../../' + path


def render(domain, label, entries):
    rows = catalogue_rows(domain)
    out = [f'# {label} hub', '',
           '*Generated by `tools/domains/build_hubs.py` from `shared/domain-tags.json` and '
           f'[`literature-library.md`](literature-library.md). Do not edit by hand.*', '',
           f'Everything in the knowledge base tagged **{domain}**: the measurement-science papers '
           'that live in this module, then the device, platform, deployment and methods material '
           'that lives in Modules 1 to 4.', '']
    profiles = [e for e in entries if e['kind'] in KIND_LABEL]
    papers = [e for e in entries if e['kind'] == 'paper']
    studies = [e for e in entries if e['kind'] == 'm3-profile']
    out += ['| Where | Count |', '|---|---|', f'| Module 5 catalogue | {len(rows)} |',
            f'| Device and platform profiles | {len(profiles)} |',
            f'| Papers in Modules 1, 2 and 4 | {len(papers)} |',
            f'| Module 3 deployment profiles | {len(studies)} |', '']

    out += ['## Measurement science (this module)', '']
    section = None
    for sec, rid, title, venue in rows:
        if sec != section:
            section = sec
            out += ['', f'**{sec}**', '']
        out.append(f'- {rid}: {title}, {venue}')
    out.append('')

    def sort_key(e):
        return (e['weight'] != 'primary', e['title'].lower())

    if profiles:
        out += ['## Device and platform profiles', '']
        for e in sorted(profiles, key=sort_key):
            out.append(f'- [{e["title"]}]({link(e["file"])}) ({KIND_LABEL[e["kind"]]}, '
                       f'{e["weight"]}): {e["reason"]}')
        out.append('')

    if studies:
        out += ['## Deployments (Module 3)', '']
        for e in sorted(studies, key=sort_key):
            out.append(f'- [{e["title"]}]({link(e["file"])}) ({e["weight"]}): {e["reason"]}')
        out.append('')

    if papers:
        out += ['## Papers in other modules', '']
        for m in sorted({e['module'] for e in papers}):
            out += [f'### {MODULE_NAMES[m]}', '']
            for e in sorted((p for p in papers if p['module'] == m), key=sort_key):
                rid = f'{e["row_id"]}, ' if e.get('row_id') else ''
                doi = f' [doi]({"https://doi.org/" + e["key"]})' if e['key'].startswith('10.') else ''
                out.append(f'- {e["title"]} ({rid}{e["weight"]}; [catalogue]({link(e["file"])}))'
                           f'{doi}: {e["reason"]}')
            out.append('')
    return re.sub(r'\n{3,}', '\n\n', '\n'.join(out)).rstrip() + '\n'


def main():
    check = '--check' in sys.argv
    tags = json.load(open(TAGS, encoding='utf-8'))
    stale = []
    for domain, spec in tags['domains'].items():
        if not os.path.exists(os.path.join(M5, domain, 'literature-library.md')):
            continue
        text = render(domain, spec['label'], tags.get(domain, []))
        path = os.path.join(M5, domain, 'hub.md')
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                open(path, 'w', encoding='utf-8').write(text)
    if check and stale:
        print('Out of date: ' + ', '.join(stale))
        sys.exit(1)
    print('Hubs up to date' if check else 'Wrote: ' + (', '.join(stale) or 'nothing changed'))


if __name__ == '__main__':
    main()
